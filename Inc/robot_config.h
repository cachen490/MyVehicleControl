#define SIGN_FL             (+1.0f)         /* 左前轮 */
#define SIGN_FR             (-1.0f)         /* 右前轮 */
#define SIGN_RL             (+1.0f)         /* 左后轮 */
#define SIGN_RR             (-1.0f)         /* 右后轮 */
#define SIGN_GZ             (+1.0f)         /* 陀螺 Z 轴（yaw 速度环用） */
#define SIGN_YAW            (+1.0f)         /* 云台 Yaw 电机 */

/* ★★★ 2026-11-11 实测定为 **−1**（原来填的 +1 是错的）。
 *
 *   判据（换轴 + 标定之后做的，观测是干净的）：
 *     取 +1 时，进运行档后臂**朝偏离水平的方向加速**，一路冲到越界兜底
 *     pit_abs = 21.5° 才被断电、掉下来，然后又反复 —— 这是 P 环正反馈。
 *   既然 SIGN_PITCH_ABS = +1 是对的，正反馈就只能是 SIGN_PIT 的符号错：
 *     PIT·ABS = +1 却失稳  ⇒  sign(Kt) = −1  ⇒  正电压让臂往**下**走。
 *   代入稳定条件 PIT·ABS = sign(Kt)：+1 × (−1) = −1 ✔ 一致。
 *
 *   ★ 这条不需要再"试"了：它是从一次完整观测（方向 + 触发点 + 反复）推出来的。
 *     以后要复核，给 pitch 一个小的已知正电压（临时改 Gimbal_Task 的 v[M_PITCH]），
 *     看臂往上还是往下，别从"往哪顶"反推 —— 那是这次反复走弯路的原因。 */
#define SIGN_PIT            (-1.0f)         /* 云台 Pitch 电机 */

