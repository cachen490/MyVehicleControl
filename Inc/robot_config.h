/* ==================== 底盘跟随云台（任务书第 3 条）====================
 *
 * 要的效果：云台用摇杆转到哪，底盘就跟着转到哪，让"云台相对底盘的角度"
 *           一直保持在车头（行程中点 90°）。这样 yaw 永远不会撞限位挡块。
 *
 * ★★★ "云台追底盘"和"底盘追云台"闭环的是**同一个 rel**，但基准反了，
 *      所以最终效果完全不同 —— 这不是"换个说法而已"：
 *
 *   ┌ 云台追底盘（gimbal.c 里旧的 s_yaw_follow）──────────────────────┐
 *   │ 基准 = 底盘。底盘转到哪，云台就用 6020 转过去贴合它。          │
 *   │ • 镜头的绝对指向 = 底盘朝向 + 90°  →  **车头一转，镜头跟着转** │
 *   │ • 底盘相对云台累计转 90° 就把云台顶到挡块上，180° 行程不够用   │
 *   │ • 只有 6020 在动，带宽高，rel 守得很紧                          │
 *   └────────────────────────────────────────────────────────────────┘
 *
 *   ┌ 底盘追云台（本段实现）──────────────────────────────────────────┐
 *   │ 基准 = 云台的绝对指向（云台锁大地，陀螺速度环把 ω 压到 0）。    │
 *   │ rel 一变，就用四个轮子把**底盘**转过去贴合云台。                │
 *   │ • 镜头指向完全由摇杆决定，**底盘只是"在下面摆正"**              │
 *   │ • rel 永远被拉回中点，行程一点不消耗，底盘可以无限转            │
 *   │ • 出力的是轮子，带宽低（地面摩擦、打滑），rel 守得松一些        │
 *   └────────────────────────────────────────────────────────────────┘
 *
 *   一句话：一个让镜头跟着车走，一个让车跟着镜头摆。任务书第 3 条要的是后者。
 *
 * ★ 两套不能同时开：闭环的是同一个 rel，同时开就是两个环抢一个被控量，
 *   而且 s_yaw_follow 会把目标锁在"当前值"上，和跟随环的目标（车头角）直接冲突。
 *   所以 YAW_FOLLOW_IMPL = 0 时 app.c 恒定传 Gimbal_SetYawFollow(0)，
 *   云台只管锁大地，跟随全交给底盘。
 *
 * 控制律（推导）：rel = θ_云台 − θ_底盘，要求 rel 稳住不动
 *     d(rel)/dt = ω_云台 − ω_底盘 = 0   →   ω_底盘 = ω_云台
 *   所以底盘转速 = 【云台当前角速度】(前馈) + 【位置误差修正】(P)：
 *       wz = SIGN × ( FF × ω_云台 − KP × err ),  err = 车头角 − rel
 *   ★ P 项对 err 是**减号**，别写反：err > 0 表示 rel 小于车头角，
 *     要把 rel 拉大 → d(rel)/dt = ω_云台 − ω_底盘 > 0 → ω_底盘 要**小于** ω_云台
 *     → 补偿量是负的 → 减号。写成加号就是正反馈，一进跟随就往一边转到底。
 *
 *   只有 P 没有前馈的话，云台匀速转时会永远滞后 err = ω/KP，
 *   云台 1rad/s、KP=5 时滞后 11.5°，肉眼能看出来。FF 就是用来消这个的。 */

/* 位置误差(rad) → 底盘角速度(rad/s)。和云台外环同量纲。
 * 5.0 表示偏 10°(0.17rad) 时底盘用 0.87rad/s 去追，约 0.2 秒到位。 */
#define CHASSIS_FOLLOW_KP    5.0f

/* 前馈系数。1.0 = 完全按云台角速度补偿；觉得底盘"抢跑"或抖，降到 0.6~0.8。
 * 给 0 就退回纯 P，云台转得快时会看到明显滞后。 */
#define CHASSIS_FOLLOW_FF    1.0f

/* 位置误差死区，rad。云台停住后底盘会在目标附近小幅来回蹭，
 * 加死区让它彻底安静。1° 足够，比这大就会出现"云台偏了一点地盘不理"的观感。 */
#define CHASSIS_FOLLOW_DB    (1.0f * DEG2RAD)

/* ★ 前馈源死区 + 输出死区（治"底盘慢慢蹭一点"）。
 *
 *   根因：err 进了 CHASSIS_FOLLOW_DB 之后 err_db = 0，但前馈项
 *         FF × Gimbal_GetYawRate() 用的是陀螺原始角速度，**并没有跟着归零**。
 *         陀螺扣零偏后仍有残留，0.01 rad/s = 0.57°/s ⇒ 10 秒蹭 6°。
 *         **死区只能挡住 P，挡不住 FF** —— 这是该控制律的结构性漏洞。
 *
 *   FF_DB  前馈源死区：云台转速低于它就当"没在转"，前馈不起作用。
 *          0.05 rad/s ≈ 2.9°/s，这个量级上陀螺残留和真实转动已分不开。
 *   W_DB   输出死区：算出的角速度低于它就置 0。0.03 rad/s ≈ 1.7°/s，
 *          比轮子摩擦死区还小，不影响任何真实运动。 */
#define CHASSIS_FOLLOW_FF_DB 0.05f
#define CHASSIS_FOLLOW_W_DB  0.03f

/* ★★★ 跟随方向，+1 / -1。填错了是**正反馈**：云台往左偏，底盘也往左跑，
 *      相对角越偏越大，最后顶着挡块转圈。
 *
 *   ★ 2026-11-11 实测：+1 是反的（云台不在中位时底盘朝"偏离"的方向转），
 *     已改为 -1。判据就是这次的现象本身，不用再测一遍 ——
 *     静态偏角下前馈 = 0，只有 P 在出力，所以静态就发散 ⟺ 就是这个符号。
 *
 *   复测方法（换机构/改接线后要重做）：
 *     1. 用手把云台相对底盘推偏约 30°（云台不动、底盘不动，纯角度差）；
 *     2. 通电进底盘随动模式，看底盘往哪边转：
 *          - 往"缩小这个偏差"的方向转 → 符号对了，等它自己回正；
 *          - 往"越偏越远"的方向转 → 立刻断电，把这个宏取反。
 *   ★ 判断"缩小还是扩大"只看底盘转的方向对不对，别看云台。
 *   ★ 别在错的符号下反复试：偏 92° 就会把云台顶到挡块上，
 *     虽然 CHASSIS_FOLLOW_FAULT_ANGLE 会闩锁停转，但挡块每次都在受力。 */
#define SIGN_CHASSIS_FOLLOW  (-1.0f)

/* 跟随环输出给底盘的角速度上限，rad/s。
 *
 * ★ 这个值同时就是"符号填反时的破坏力上限"，所以第一次上电先给 1.5，
 *   确认 SIGN_CHASSIS_FOLLOW 这 1 bit 对了，再放开到 3.0。
 *   3.0 rad/s ≈ 172°/s，已经比推杆快得多，再大没有意义。
 *   （跑飞时底盘会把云台顶过挡块，转速越低，挡块吃的冲击越小。） */
#define CHASSIS_FOLLOW_W_MAX  1.5f

/* 跑飞闩锁门限，rad。|err| 超过它就判定"不是跟随、是正反馈跑飞"，底盘停转。
 *
 *   ★ 门限必须**小于几何极限**，否则永远不触发：按实测 ecd 算，
 *     车头到两侧挡块各只有 92°，云台顶死后 |err| 就此冻结，
 *     门限设在 92° 以上等于没有保护，底盘会一直转下去。
 *
 *   ★ 门限也不能太小：|err| 不总是稳态误差，把云台相对车头拧过大角度就会超过它。
 *     以前用 70° 时，拧过一次就闩死，现象是"底盘完全不随动"，
 *     而且只有切一次停车档才恢复 —— 极难查。
 *
 *   ⇒ 85°：比几何极限早 7°，真跑飞照样在顶到挡块前停；
 *     配合下面的 CLEAR 门限做**回差自动恢复**，不再一锁到底。
 *     安全上没有损失：真跑飞时 err 只会一路顶向 92°，不会自己回到 78°。 */
#define CHASSIS_FOLLOW_FAULT_ANGLE  (85.0f * DEG2RAD)

/* 闩锁自动解除门限，rad。|err| 回到这个范围内就解锁。
 * 必须小于上面的门限，否则会在边界反复锁/解锁。差 7° 够用。 */
#define CHASSIS_FOLLOW_FAULT_CLEAR  (78.0f * DEG2RAD)

/* 下位档（跟随）用哪套实现：
 *   0 = 底盘追云台（推荐，任务书第 3 条；云台永远在行程中点，不撞块）
 *   1 = 云台追底盘（旧实现 s_yaw_follow；底盘累计转 90° 就顶死限位）
 * 改了必须重新编译。两套互斥，理由见上面那段。 */
#define YAW_FOLLOW_IMPL      0

